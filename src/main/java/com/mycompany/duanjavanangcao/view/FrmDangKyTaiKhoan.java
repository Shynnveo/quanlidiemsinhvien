    private void btnDangKyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDangKyActionPerformed
        String maSinhVien = txtMaSinhVien.getText();
        String tenDangNhap = txtTenDangNhap.getText();
        String matKhau = new String(txtMatKhau.getPassword());
        String xacNhanMatKhau = new String(txtXacNhanMatKhau.getPassword());

        try {
            SinhVien sv = dangKyService.dangKyTaiKhoan(maSinhVien, tenDangNhap, matKhau, xacNhanMatKhau);

            JOptionPane.showMessageDialog(this,
                    "Chúc mừng! Đăng ký tài khoản thành công cho sinh viên:\n"
                    + "- Họ và tên: " + sv.getHoTen() + "\n"
                    + "- Mã sinh viên: " + sv.getMaSinhVien() + "\n"
                    + "- Tên đăng nhập: " + tenDangNhap.trim() + "\n\n"
                    + "Bạn có thể sử dụng tài khoản này để đăng nhập ngay bây giờ.",
                    "Đăng ký thành công",
                    JOptionPane.INFORMATION_MESSAGE);

            // Chuyển hướng quay lại màn hình đăng nhập
            new FrmDangNhap().setVisible(true);
            this.dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                    ex.getMessage(),
                    "Lỗi đăng ký tài khoản",
                    JOptionPane.ERROR_MESSAGE);
            txtMatKhau.setText("");
            txtXacNhanMatKhau.setText("");
            txtMatKhau.requestFocus();
        }
    }//GEN-LAST:event_btnDangKyActionPerformed

