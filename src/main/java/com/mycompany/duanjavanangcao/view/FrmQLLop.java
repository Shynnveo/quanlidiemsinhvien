    private void tblLopMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblLopMouseClicked
        int selectedRow = tblLop.getSelectedRow();
        if (selectedRow >= 0 && danhSachLop != null && selectedRow < danhSachLop.size()) {
            Lop lop = danhSachLop.get(selectedRow);
            selectedLopId = lop.getLopId();

            txtMaLop.setText(lop.getMaLop());
            txtMaLop.setEditable(false); // Không sửa mã lớp (khóa chính nghiệp vụ)
            txtTenLop.setText(lop.getTenLop());
            txtKhoaHoc.setText(lop.getKhoaHoc() != null ? lop.getKhoaHoc() : "");
            txtNganhHoc.setText(lop.getNganhHoc() != null ? lop.getNganhHoc() : "");
            txtKhoa.setText(lop.getKhoa() != null ? lop.getKhoa() : "");
            chkTrangThai.setSelected(lop.isTrangThai());
        }
    }//GEN-LAST:event_tblLopMouseClicked

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String maLop = txtMaLop.getText().trim();
        String tenLop = txtTenLop.getText().trim();

        if (maLop.isEmpty() || tenLop.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ Mã lớp và Tên lớp!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Lop lop = new Lop();
        lop.setMaLop(maLop);
        lop.setTenLop(tenLop);
        lop.setKhoaHoc(txtKhoaHoc.getText().trim());
        lop.setNganhHoc(txtNganhHoc.getText().trim());
        lop.setKhoa(txtKhoa.getText().trim());
        lop.setTrangThai(chkTrangThai.isSelected());

        if (lopDAO.insert(lop)) {
            JOptionPane.showMessageDialog(this, "Thêm lớp học thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại! Mã lớp có thể đã tồn tại.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        if (selectedLopId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn lớp học trên bảng để sửa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String tenLop = txtTenLop.getText().trim();
        if (tenLop.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tên lớp không được để trống!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Lop lop = new Lop();
        lop.setLopId(selectedLopId);
        lop.setMaLop(txtMaLop.getText().trim());
        lop.setTenLop(tenLop);
        lop.setKhoaHoc(txtKhoaHoc.getText().trim());
        lop.setNganhHoc(txtNganhHoc.getText().trim());
        lop.setKhoa(txtKhoa.getText().trim());
        lop.setTrangThai(chkTrangThai.isSelected());

        if (lopDAO.update(lop)) {
            JOptionPane.showMessageDialog(this, "Cập nhật lớp học thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        if (selectedLopId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn lớp học trên bảng để xóa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc chắn muốn xóa lớp [" + txtMaLop.getText() + "] không?",
                "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (lopDAO.delete(selectedLopId)) {
                JOptionPane.showMessageDialog(this, "Xóa lớp học thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
                lamMoiForm();
                taiDuLieuLenBang();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Không thể xóa", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnXoaActionPerformed

