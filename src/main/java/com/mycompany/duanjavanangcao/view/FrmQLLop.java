    private void taiDuLieuLenBang() {
        danhSachLop = lopDAO.findAll();
        hienThiLenBang(danhSachLop);
    }

    private void hienThiLenBang(List<Lop> list) {
        DefaultTableModel model = (DefaultTableModel) tblLop.getModel();
        model.setRowCount(0);

        int stt = 1;
        for (Lop lop : list) {
            model.addRow(new Object[]{
                stt++,
                lop.getMaLop(),
                lop.getTenLop(),
                lop.getKhoaHoc() != null ? lop.getKhoaHoc() : "",
                lop.getNganhHoc() != null ? lop.getNganhHoc() : "",
                lop.getKhoa() != null ? lop.getKhoa() : "",
                lop.isTrangThai() ? "Hoạt động" : "Ngừng"
            });
        }
    }

