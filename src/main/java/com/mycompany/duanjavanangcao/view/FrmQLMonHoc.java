    private void taiDuLieuLenBang() {
        danhSachMon = monHocDAO.findAll();
        hienThiLenBang(danhSachMon);
    }

    private void hienThiLenBang(List<MonHoc> list) {
        DefaultTableModel model = (DefaultTableModel) tblMonHoc.getModel();
        model.setRowCount(0);

        int stt = 1;
        for (MonHoc mh : list) {
            model.addRow(new Object[]{
                stt++,
                mh.getMaMonHoc(),
                mh.getTenMonHoc(),
                mh.getSoTinChi(),
                mh.getMoTa() != null ? mh.getMoTa() : "",
                mh.isTrangThai() ? "Đang dạy" : "Ngừng"
            });
        }
    }

