    private void tblMonHocMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMonHocMouseClicked
        int selectedRow = tblMonHoc.getSelectedRow();
        if (selectedRow >= 0 && danhSachMon != null && selectedRow < danhSachMon.size()) {
            MonHoc mh = danhSachMon.get(selectedRow);
            selectedMonId = mh.getMonHocId();

            txtMaMon.setText(mh.getMaMonHoc());
            txtMaMon.setEditable(false);
            txtTenMon.setText(mh.getTenMonHoc());
            txtSoTinChi.setText(String.valueOf(mh.getSoTinChi()));
            txtMoTa.setText(mh.getMoTa() != null ? mh.getMoTa() : "");
            chkTrangThai.setSelected(mh.isTrangThai());
        }
    }//GEN-LAST:event_tblMonHocMouseClicked

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String maMon = txtMaMon.getText().trim();
        String tenMon = txtTenMon.getText().trim();
        String tcStr = txtSoTinChi.getText().trim();

        if (maMon.isEmpty() || tenMon.isEmpty() || tcStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ Mã môn, Tên môn và Số tín chỉ!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int soTinChi;
        try {
            soTinChi = Integer.parseInt(tcStr);
            if (soTinChi <= 0 || soTinChi > 15) {
                JOptionPane.showMessageDialog(this, "Số tín chỉ phải từ 1 đến 15!", "Số liệu không hợp lệ", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Số tín chỉ phải là số nguyên dương!", "Sai định dạng", JOptionPane.WARNING_MESSAGE);
            return;
        }

        MonHoc mh = new MonHoc();
        mh.setMaMonHoc(maMon);
        mh.setTenMonHoc(tenMon);
        mh.setSoTinChi(soTinChi);
        mh.setMoTa(txtMoTa.getText().trim());
        mh.setTrangThai(chkTrangThai.isSelected());

        if (monHocDAO.insert(mh)) {
            JOptionPane.showMessageDialog(this, "Thêm môn học thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại! Mã môn học có thể đã tồn tại.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        if (selectedMonId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn môn học trên bảng để sửa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String tenMon = txtTenMon.getText().trim();
        String tcStr = txtSoTinChi.getText().trim();
        if (tenMon.isEmpty() || tcStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tên môn và số tín chỉ không được để trống!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int soTinChi;
        try {
            soTinChi = Integer.parseInt(tcStr);
            if (soTinChi <= 0 || soTinChi > 15) {
                JOptionPane.showMessageDialog(this, "Số tín chỉ phải từ 1 đến 15!", "Số liệu không hợp lệ", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Số tín chỉ phải là số nguyên dương!", "Sai định dạng", JOptionPane.WARNING_MESSAGE);
            return;
        }

        MonHoc mh = new MonHoc();
        mh.setMonHocId(selectedMonId);
        mh.setMaMonHoc(txtMaMon.getText().trim());
        mh.setTenMonHoc(tenMon);
        mh.setSoTinChi(soTinChi);
        mh.setMoTa(txtMoTa.getText().trim());
        mh.setTrangThai(chkTrangThai.isSelected());

        if (monHocDAO.update(mh)) {
            JOptionPane.showMessageDialog(this, "Cập nhật môn học thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        if (selectedMonId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn môn học trên bảng để xóa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc chắn muốn xóa môn học [" + txtMaMon.getText() + " - " + txtTenMon.getText() + "] không?",
                "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (monHocDAO.delete(selectedMonId)) {
                JOptionPane.showMessageDialog(this, "Xóa môn học thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
                lamMoiForm();
                taiDuLieuLenBang();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Không thể xóa", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnXoaActionPerformed

