    private void taiDuLieuLenBang() {
        danhSachGV = giangVienDAO.findAll();
        hienThiLenBang(danhSachGV);
    }

    private void hienThiLenBang(List<GiangVien> list) {
        DefaultTableModel model = (DefaultTableModel) tblGiangVien.getModel();
        model.setRowCount(0);

        int stt = 1;
        for (GiangVien gv : list) {
            model.addRow(new Object[]{
                stt++,
                gv.getMaGiangVien(),
                gv.getHoTen(),
                gv.getEmail() != null ? gv.getEmail() : "",
                gv.getSoDienThoai() != null ? gv.getSoDienThoai() : "",
                gv.getKhoa() != null ? gv.getKhoa() : ""
            });
        }
    }

