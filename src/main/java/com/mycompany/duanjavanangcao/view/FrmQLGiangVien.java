    private void tblGiangVienMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblGiangVienMouseClicked
        int selectedRow = tblGiangVien.getSelectedRow();
        if (selectedRow >= 0 && danhSachGV != null && selectedRow < danhSachGV.size()) {
            GiangVien gv = danhSachGV.get(selectedRow);
            selectedGVId = gv.getGiangVienId();

            txtMaGV.setText(gv.getMaGiangVien());
            txtMaGV.setEditable(false);
            txtHoTen.setText(gv.getHoTen());
            txtEmail.setText(gv.getEmail() != null ? gv.getEmail() : "");
            txtSoDienThoai.setText(gv.getSoDienThoai() != null ? gv.getSoDienThoai() : "");
            txtKhoa.setText(gv.getKhoa() != null ? gv.getKhoa() : "");
        }
    }//GEN-LAST:event_tblGiangVienMouseClicked

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String maGV = txtMaGV.getText().trim();
        String hoTen = txtHoTen.getText().trim();

        if (maGV.isEmpty() || hoTen.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ Mã giảng viên và Họ tên!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        GiangVien gv = new GiangVien();
        gv.setMaGiangVien(maGV);
        gv.setHoTen(hoTen);
        gv.setEmail(txtEmail.getText().trim());
        gv.setSoDienThoai(txtSoDienThoai.getText().trim());
        gv.setKhoa(txtKhoa.getText().trim());

        if (giangVienDAO.insert(gv)) {
            JOptionPane.showMessageDialog(this, "Thêm giảng viên thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại! Mã giảng viên có thể đã tồn tại.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        if (selectedGVId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn giảng viên trên bảng để sửa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String hoTen = txtHoTen.getText().trim();
        if (hoTen.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Họ tên giảng viên không được để trống!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        GiangVien gv = new GiangVien();
        gv.setGiangVienId(selectedGVId);
        gv.setMaGiangVien(txtMaGV.getText().trim());
        gv.setHoTen(hoTen);
        gv.setEmail(txtEmail.getText().trim());
        gv.setSoDienThoai(txtSoDienThoai.getText().trim());
        gv.setKhoa(txtKhoa.getText().trim());

        if (giangVienDAO.update(gv)) {
            JOptionPane.showMessageDialog(this, "Cập nhật giảng viên thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        if (selectedGVId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn giảng viên trên bảng để xóa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc chắn muốn xóa giảng viên [" + txtMaGV.getText() + " - " + txtHoTen.getText() + "] không?",
                "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (giangVienDAO.delete(selectedGVId)) {
                JOptionPane.showMessageDialog(this, "Xóa giảng viên thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
                lamMoiForm();
                taiDuLieuLenBang();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Không thể xóa", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnXoaActionPerformed

