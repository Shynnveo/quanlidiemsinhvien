    private void tblSinhVienMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSinhVienMouseClicked
        int selectedRow = tblSinhVien.getSelectedRow();
        if (selectedRow >= 0 && danhSachSV != null && selectedRow < danhSachSV.size()) {
            SinhVien sv = danhSachSV.get(selectedRow);
            selectedSVId = sv.getSinhVienId();

            txtMaSV.setText(sv.getMaSinhVien());
            txtMaSV.setEditable(false);
            txtHoTen.setText(sv.getHoTen());
            txtNgaySinh.setText(sv.getNgaySinh() != null ? sv.getNgaySinh().toString() : "");
            cboGioiTinh.setSelectedItem(sv.getGioiTinh() != null ? sv.getGioiTinh() : "Nam");
            txtEmail.setText(sv.getEmail() != null ? sv.getEmail() : "");
            txtSoDienThoai.setText(sv.getSoDienThoai() != null ? sv.getSoDienThoai() : "");
            txtDiaChi.setText(sv.getDiaChi() != null ? sv.getDiaChi() : "");
            cboTrangThai.setSelectedItem(sv.getTrangThai() != null ? sv.getTrangThai() : "Đang học");

            // Chọn lớp tương ứng trên combobox
            if (sv.getLopId() != null && danhSachLop != null) {
                for (int i = 0; i < danhSachLop.size(); i++) {
                    if (danhSachLop.get(i).getLopId() == sv.getLopId()) {
                        cboLop.setSelectedIndex(i + 1);
                        break;
                    }
                }
            } else {
                cboLop.setSelectedIndex(0);
            }
        }
    }//GEN-LAST:event_tblSinhVienMouseClicked

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String maSV = txtMaSV.getText().trim();
        String hoTen = txtHoTen.getText().trim();

        if (maSV.isEmpty() || hoTen.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ Mã sinh viên và Họ tên!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        SinhVien sv = new SinhVien();
        sv.setMaSinhVien(maSV);
        sv.setHoTen(hoTen);

        String nsStr = txtNgaySinh.getText().trim();
        if (!nsStr.isEmpty()) {
            try {
                sv.setNgaySinh(Date.valueOf(nsStr));
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Định dạng ngày sinh không hợp lệ (Phải là yyyy-MM-dd, ví dụ 2005-04-12)!", "Lỗi định dạng", JOptionPane.WARNING_MESSAGE);
                return;
            }
        }

        sv.setGioiTinh((String) cboGioiTinh.getSelectedItem());
        sv.setTrangThai((String) cboTrangThai.getSelectedItem());
        sv.setEmail(txtEmail.getText().trim());
        sv.setSoDienThoai(txtSoDienThoai.getText().trim());
        sv.setDiaChi(txtDiaChi.getText().trim());

        int lopIdx = cboLop.getSelectedIndex();
        if (lopIdx > 0 && danhSachLop != null) {
            sv.setLopId(danhSachLop.get(lopIdx - 1).getLopId());
        }

        if (sinhVienDAO.insert(sv)) {
            JOptionPane.showMessageDialog(this, "Thêm sinh viên thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại! Mã sinh viên có thể đã tồn tại.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        if (selectedSVId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sinh viên trên bảng để sửa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String hoTen = txtHoTen.getText().trim();
        if (hoTen.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Họ tên không được để trống!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        SinhVien sv = new SinhVien();
        sv.setSinhVienId(selectedSVId);
        sv.setMaSinhVien(txtMaSV.getText().trim());
        sv.setHoTen(hoTen);

        String nsStr = txtNgaySinh.getText().trim();
        if (!nsStr.isEmpty()) {
            try {
                sv.setNgaySinh(Date.valueOf(nsStr));
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Định dạng ngày sinh không hợp lệ (yyyy-MM-dd)!", "Lỗi định dạng", JOptionPane.WARNING_MESSAGE);
                return;
            }
        }

        sv.setGioiTinh((String) cboGioiTinh.getSelectedItem());
        sv.setTrangThai((String) cboTrangThai.getSelectedItem());
        sv.setEmail(txtEmail.getText().trim());
        sv.setSoDienThoai(txtSoDienThoai.getText().trim());
        sv.setDiaChi(txtDiaChi.getText().trim());

        int lopIdx = cboLop.getSelectedIndex();
        if (lopIdx > 0 && danhSachLop != null) {
            sv.setLopId(danhSachLop.get(lopIdx - 1).getLopId());
        }

        if (sinhVienDAO.update(sv)) {
            JOptionPane.showMessageDialog(this, "Cập nhật thông tin sinh viên thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        if (selectedSVId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sinh viên trên bảng để xóa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc chắn muốn xóa sinh viên [" + txtMaSV.getText() + " - " + txtHoTen.getText() + "] không?",
                "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (sinhVienDAO.delete(selectedSVId)) {
                JOptionPane.showMessageDialog(this, "Xóa sinh viên thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
                lamMoiForm();
                taiDuLieuLenBang();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Không thể xóa", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnXoaActionPerformed

