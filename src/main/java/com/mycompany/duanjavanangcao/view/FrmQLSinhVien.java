    private void taiDanhSachLopVaoCombobox() {
        danhSachLop = lopDAO.findAll();

        DefaultComboBoxModel<String> modelLop = new DefaultComboBoxModel<>();
        modelLop.addElement("-- Chọn lớp --");
        for (Lop lop : danhSachLop) {
            modelLop.addElement(lop.getMaLop() + " - " + lop.getTenLop());
        }
        cboLop.setModel(modelLop);

        DefaultComboBoxModel<String> modelLocLop = new DefaultComboBoxModel<>();
        modelLocLop.addElement("-- Tất cả các lớp --");
        for (Lop lop : danhSachLop) {
            modelLocLop.addElement(lop.getMaLop());
        }
        cboLocLop.setModel(modelLocLop);
    }

    private void taiDuLieuLenBang() {
        danhSachSV = sinhVienDAO.findAll();
        hienThiLenBang(danhSachSV);
    }

    private void hienThiLenBang(List<SinhVien> list) {
        DefaultTableModel model = (DefaultTableModel) tblSinhVien.getModel();
        model.setRowCount(0);

        int stt = 1;
        for (SinhVien sv : list) {
            model.addRow(new Object[]{
                stt++,
                sv.getMaSinhVien(),
                sv.getHoTen(),
                sv.getGioiTinh() != null ? sv.getGioiTinh() : "",
                sv.getNgaySinh() != null ? sv.getNgaySinh().toString() : "",
                sv.getSoDienThoai() != null ? sv.getSoDienThoai() : "",
                sv.getEmail() != null ? sv.getEmail() : "",
                sv.getTrangThai() != null ? sv.getTrangThai() : ""
            });
        }
    }

