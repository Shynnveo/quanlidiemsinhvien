    private void btnTimKiemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimKiemActionPerformed
        String keyword = txtTimKiem.getText().trim();
        if (keyword.isEmpty()) {
            taiDuLieuLenBang();
        } else {
            danhSachSV = sinhVienDAO.search(keyword);
            hienThiLenBang(danhSachSV);
        }
    }//GEN-LAST:event_btnTimKiemActionPerformed

    private void cboLocLopActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboLocLopActionPerformed
        int idx = cboLocLop.getSelectedIndex();
        if (idx <= 0 || danhSachLop == null) {
            taiDuLieuLenBang();
        } else {
            int lopId = danhSachLop.get(idx - 1).getLopId();
            danhSachSV = sinhVienDAO.findByLop(lopId);
            hienThiLenBang(danhSachSV);
        }
    }//GEN-LAST:event_cboLocLopActionPerformed

