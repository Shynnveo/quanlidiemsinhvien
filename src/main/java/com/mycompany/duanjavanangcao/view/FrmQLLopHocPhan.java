    private void tblLopHocPhanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblLopHocPhanMouseClicked
        int selectedRow = tblLopHocPhan.getSelectedRow();
        if (selectedRow >= 0 && danhSachLHP != null && selectedRow < danhSachLHP.size()) {
            LopHocPhan lhp = danhSachLHP.get(selectedRow);
            selectedLHPId = lhp.getLopHocPhanId();

            txtMaLHP.setText(lhp.getMaLopHocPhan());
            txtMaLHP.setEditable(false);
            txtNhom.setText(lhp.getNhom() != null ? lhp.getNhom() : "01");
            txtSiSo.setText(lhp.getSiSoToiDa() != null ? String.valueOf(lhp.getSiSoToiDa()) : "40");
            txtPhongHoc.setText(lhp.getPhongHoc() != null ? lhp.getPhongHoc() : "");
            txtLichHoc.setText(lhp.getLichHoc() != null ? lhp.getLichHoc() : "");
            cboTrangThai.setSelectedItem(lhp.getTrangThai() != null ? lhp.getTrangThai() : "Đang mở");

            // Chọn môn học
            if (danhSachMon != null) {
                for (int i = 0; i < danhSachMon.size(); i++) {
                    if (danhSachMon.get(i).getMonHocId() == lhp.getMonHocId()) {
                        cboMonHoc.setSelectedIndex(i + 1);
                        break;
                    }
                }
            }

            // Chọn học kỳ
            if (danhSachHK != null) {
                for (int i = 0; i < danhSachHK.size(); i++) {
                    if (danhSachHK.get(i).getHocKyId() == lhp.getHocKyId()) {
                        cboHocKy.setSelectedIndex(i + 1);
                        break;
                    }
                }
            }

            // Chọn giảng viên
            if (lhp.getGiangVienId() != null && danhSachGV != null) {
                for (int i = 0; i < danhSachGV.size(); i++) {
                    if (danhSachGV.get(i).getGiangVienId() == lhp.getGiangVienId()) {
                        cboGiangVien.setSelectedIndex(i + 1);
                        break;
                    }
                }
            } else {
                cboGiangVien.setSelectedIndex(0);
            }
        }
    }//GEN-LAST:event_tblLopHocPhanMouseClicked

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String maLHP = txtMaLHP.getText().trim();
        int monIdx = cboMonHoc.getSelectedIndex();
        int hkIdx = cboHocKy.getSelectedIndex();

        if (maLHP.isEmpty() || monIdx <= 0 || hkIdx <= 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập Mã lớp HP, chọn Môn học và Học kỳ!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int siSo = 40;
        try {
            siSo = Integer.parseInt(txtSiSo.getText().trim());
        } catch (NumberFormatException ignored) {
        }

        LopHocPhan lhp = new LopHocPhan();
        lhp.setMaLopHocPhan(maLHP);
        lhp.setMonHocId(danhSachMon.get(monIdx - 1).getMonHocId());
        lhp.setHocKyId(danhSachHK.get(hkIdx - 1).getHocKyId());

        int gvIdx = cboGiangVien.getSelectedIndex();
        if (gvIdx > 0 && danhSachGV != null) {
            lhp.setGiangVienId(danhSachGV.get(gvIdx - 1).getGiangVienId());
        }

        lhp.setNhom(txtNhom.getText().trim());
        lhp.setSiSoToiDa(siSo);
        lhp.setPhongHoc(txtPhongHoc.getText().trim());
        lhp.setLichHoc(txtLichHoc.getText().trim());
        lhp.setTrangThai((String) cboTrangThai.getSelectedItem());

        if (lhpDAO.insert(lhp)) {
            JOptionPane.showMessageDialog(this, "Thêm lớp học phần thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại! Mã lớp học phần có thể đã tồn tại.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnThemActionPerformed

