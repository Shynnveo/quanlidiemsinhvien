    private void taiDuLieuCombobox() {
        // 1. Môn học
        danhSachMon = monHocDAO.findAll();
        DefaultComboBoxModel<String> modelMon = new DefaultComboBoxModel<>();
        modelMon.addElement("-- Chọn môn học --");
        for (MonHoc mh : danhSachMon) {
            modelMon.addElement(mh.getMaMonHoc() + " - " + mh.getTenMonHoc());
        }
        cboMonHoc.setModel(modelMon);

        // 2. Học kỳ
        danhSachHK = hocKyDAO.findAll();
        DefaultComboBoxModel<String> modelHK = new DefaultComboBoxModel<>();
        modelHK.addElement("-- Chọn học kỳ --");
        for (HocKy hk : danhSachHK) {
            modelHK.addElement(hk.getMaHocKy() + " (" + hk.getNamHoc() + ")");
        }
        cboHocKy.setModel(modelHK);

        // 3. Giảng viên
        danhSachGV = giangVienDAO.findAll();
        DefaultComboBoxModel<String> modelGV = new DefaultComboBoxModel<>();
        modelGV.addElement("-- Chọn giảng viên --");
        for (GiangVien gv : danhSachGV) {
            modelGV.addElement(gv.getMaGiangVien() + " - " + gv.getHoTen());
        }
        cboGiangVien.setModel(modelGV);
    }

    private void taiDuLieuLenBang() {
        danhSachLHP = lhpDAO.findAll();
        hienThiLenBang(danhSachLHP);
    }

    private void hienThiLenBang(List<LopHocPhan> list) {
        DefaultTableModel model = (DefaultTableModel) tblLopHocPhan.getModel();
        model.setRowCount(0);

        int stt = 1;
        for (LopHocPhan lhp : list) {
            String lichPhong = (lhp.getLichHoc() != null ? lhp.getLichHoc() : "")
                    + (lhp.getPhongHoc() != null ? " (" + lhp.getPhongHoc() + ")" : "");
            model.addRow(new Object[]{
                stt++,
                lhp.getMaLopHocPhan(),
                lhp.getTenMonHoc() != null ? lhp.getTenMonHoc() : "",
                lhp.getTenHocKy() != null ? lhp.getTenHocKy() : "",
                lhp.getTenGiangVien() != null ? lhp.getTenGiangVien() : "Chưa gán",
                lhp.getNhom() != null ? lhp.getNhom() : "",
                lhp.getSiSoToiDa() != null ? lhp.getSiSoToiDa() : 40,
                lichPhong,
                lhp.getTrangThai() != null ? lhp.getTrangThai() : ""
            });
        }
    }

