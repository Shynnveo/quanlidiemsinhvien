    private void taiDuLieuLenBang() {
        danhSachHK = hocKyDAO.findAll();
        hienThiLenBang(danhSachHK);
    }

    private void hienThiLenBang(List<HocKy> list) {
        DefaultTableModel model = (DefaultTableModel) tblHocKy.getModel();
        model.setRowCount(0);

        int stt = 1;
        for (HocKy hk : list) {
            model.addRow(new Object[]{
                stt++,
                hk.getMaHocKy(),
                hk.getTenHocKy(),
                hk.getNamHoc(),
                hk.getNgayBatDau() != null ? hk.getNgayBatDau().toString() : "",
                hk.getNgayKetThuc() != null ? hk.getNgayKetThuc().toString() : "",
                hk.getTrangThai() != null ? hk.getTrangThai() : ""
            });
        }
    }

