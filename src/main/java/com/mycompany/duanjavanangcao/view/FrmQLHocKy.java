    private void tblHocKyMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblHocKyMouseClicked
        int selectedRow = tblHocKy.getSelectedRow();
        if (selectedRow >= 0 && danhSachHK != null && selectedRow < danhSachHK.size()) {
            HocKy hk = danhSachHK.get(selectedRow);
            selectedHKId = hk.getHocKyId();

            txtMaHK.setText(hk.getMaHocKy());
            txtMaHK.setEditable(false);
            txtTenHK.setText(hk.getTenHocKy());
            txtNamHoc.setText(hk.getNamHoc());
            txtNgayBatDau.setText(hk.getNgayBatDau() != null ? hk.getNgayBatDau().toString() : "");
            txtNgayKetThuc.setText(hk.getNgayKetThuc() != null ? hk.getNgayKetThuc().toString() : "");
            cboTrangThai.setSelectedItem(hk.getTrangThai() != null ? hk.getTrangThai() : "Đang học");
        }
    }//GEN-LAST:event_tblHocKyMouseClicked

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String maHK = txtMaHK.getText().trim();
        String tenHK = txtTenHK.getText().trim();
        String namHoc = txtNamHoc.getText().trim();

        if (maHK.isEmpty() || tenHK.isEmpty() || namHoc.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ Mã HK, Tên học kỳ và Năm học!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        HocKy hk = new HocKy();
        hk.setMaHocKy(maHK);
        hk.setTenHocKy(tenHK);
        hk.setNamHoc(namHoc);

        String nbStr = txtNgayBatDau.getText().trim();
        String nkStr = txtNgayKetThuc.getText().trim();
        try {
            if (!nbStr.isEmpty()) hk.setNgayBatDau(Date.valueOf(nbStr));
            if (!nkStr.isEmpty()) hk.setNgayKetThuc(Date.valueOf(nkStr));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Định dạng ngày không hợp lệ (Phải là yyyy-MM-dd)!", "Lỗi định dạng", JOptionPane.WARNING_MESSAGE);
            return;
        }

        hk.setTrangThai((String) cboTrangThai.getSelectedItem());

        if (hocKyDAO.insert(hk)) {
            JOptionPane.showMessageDialog(this, "Thêm học kỳ thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại! Mã học kỳ có thể đã tồn tại.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        if (selectedHKId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn học kỳ trên bảng để sửa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String tenHK = txtTenHK.getText().trim();
        String namHoc = txtNamHoc.getText().trim();
        if (tenHK.isEmpty() || namHoc.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tên học kỳ và năm học không được để trống!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        HocKy hk = new HocKy();
        hk.setHocKyId(selectedHKId);
        hk.setMaHocKy(txtMaHK.getText().trim());
        hk.setTenHocKy(tenHK);
        hk.setNamHoc(namHoc);

        String nbStr = txtNgayBatDau.getText().trim();
        String nkStr = txtNgayKetThuc.getText().trim();
        try {
            if (!nbStr.isEmpty()) hk.setNgayBatDau(Date.valueOf(nbStr));
            if (!nkStr.isEmpty()) hk.setNgayKetThuc(Date.valueOf(nkStr));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Định dạng ngày không hợp lệ (yyyy-MM-dd)!", "Lỗi định dạng", JOptionPane.WARNING_MESSAGE);
            return;
        }

        hk.setTrangThai((String) cboTrangThai.getSelectedItem());

        if (hocKyDAO.update(hk)) {
            JOptionPane.showMessageDialog(this, "Cập nhật học kỳ thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
            lamMoiForm();
            taiDuLieuLenBang();
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        if (selectedHKId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn học kỳ trên bảng để xóa!", "Chưa chọn dữ liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc chắn muốn xóa học kỳ [" + txtMaHK.getText() + " - " + txtTenHK.getText() + "] không?",
                "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (hocKyDAO.delete(selectedHKId)) {
                JOptionPane.showMessageDialog(this, "Xóa học kỳ thành công!", "Thành công", JOptionPane.INFORMATION_MESSAGE);
                lamMoiForm();
                taiDuLieuLenBang();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Không thể xóa", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnXoaActionPerformed

